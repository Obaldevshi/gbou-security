"""Synthetic QR generated with the server's ReportLab encoder, never real pairing."""
from pathlib import Path
import base64
from io import BytesIO
from PIL import Image, ImageDraw
from reportlab.graphics.barcode.qr import QrCodeWidget

root = Path(__file__).resolve().parents[1]
url = 'https://gbousecurity.ru/#/connect/11111111-2222-4333-8444-555555555555'
qr = QrCodeWidget(url).qr
qr.make()
n = qr.getModuleCount()
scale, border = 12, 4
im = Image.new('RGB', ((n + border * 2) * scale,) * 2, 'white')
draw = ImageDraw.Draw(im)
for y, row in enumerate(qr.modules):
    for x, black in enumerate(row):
        if black:
            px, py = (x + border) * scale, (y + border) * scale
            draw.rectangle((px, py, px + scale - 1, py + scale - 1), fill='black')
buf = BytesIO()
im.save(buf, format='PNG')
folder = root / 'init-app/integration_test/fixtures'
folder.mkdir(exist_ok=True)
(folder / 'qr_fixture.dart').write_text(
    '// Generated by tools/generate_qr_test_fixture.py; synthetic, no secret.\n'
    f"const qrFixtureUrl = '{url}';\n"
    f"const qrFixtureBase64 = '{base64.b64encode(buf.getvalue()).decode()}';\n",
    encoding='utf8')
out = root / 'artifacts/visual-audit-cross-store'
out.mkdir(exist_ok=True)
im.save(out / 'synthetic-pairing-qr.png')
print('Synthetic QR fixture generated; no live request created.')
