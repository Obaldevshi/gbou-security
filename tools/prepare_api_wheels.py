"""Generate the offline CPython 3.12/Linux x86_64 deployment artifact.

Downloads unchanged wheels from official PyPI with TLS verification. Every
artifact is checked against the release's published SHA-256 before locking.
This does not install packages, modify secrets, or touch the Raspberry.
"""

from concurrent.futures import ThreadPoolExecutor
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from urllib.request import urlopen
from email.parser import BytesParser
from zipfile import ZipFile

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.specifiers import SpecifierSet
from packaging.tags import compatible_tags, cpython_tags
from packaging.utils import canonicalize_name, parse_wheel_filename


ROOT = Path(__file__).resolve().parents[1]
API = ROOT / "init-api"
BUNDLE = API / "deploy-wheels"
PLATFORMS = ["manylinux2014_x86_64", "manylinux_2_17_x86_64", "manylinux_2_28_x86_64", "manylinux_2_34_x86_64"]
TARGET_TAGS = set(cpython_tags((3, 12), abis=["cp312"], platforms=PLATFORMS))
TARGET_TAGS.update(compatible_tags((3, 12), interpreter="cp312", platforms=PLATFORMS))


def verify(wheel):
    name, version, _, tags = parse_wheel_filename(wheel.name)
    if not tags.intersection(TARGET_TAGS):
        raise ValueError("Wrong deployment platform")
    with wheel.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        release = json.load(response)
    published = next(item for item in release["urls"] if item["filename"] == wheel.name)
    if published["digests"]["sha256"] != digest:
        raise ValueError(f"PyPI checksum mismatch for {wheel.name}")
    return str(name), str(version), digest, wheel.name


def validate_dependencies(records):
    versions = {canonicalize_name(name): version for name, version, _, _ in records}
    context = default_environment()
    context.update(sys_platform="linux", os_name="posix", platform_system="Linux",
                   platform_machine="x86_64", python_version="3.12", python_full_version="3.12.0", extra="")
    for name, version, _, filename in records:
        with ZipFile(BUNDLE / filename) as archive:
            metadata = next(path for path in archive.namelist() if path.endswith(".dist-info/METADATA"))
            message = BytesParser().parsebytes(archive.read(metadata))
        if canonicalize_name(message["Name"]) != canonicalize_name(name) or message["Version"] != version:
            raise ValueError("Wheel filename and metadata differ")
        if message["Requires-Python"] and "3.12.0" not in SpecifierSet(message["Requires-Python"]):
            raise ValueError(f"Python 3.12 unsupported by {name}")
        for value in message.get_all("Requires-Dist", []):
            requirement = Requirement(value)
            if requirement.marker is not None and not requirement.marker.evaluate(context):
                continue
            installed = versions.get(canonicalize_name(requirement.name))
            if installed is None or (requirement.specifier and installed not in requirement.specifier):
                raise ValueError(f"Offline dependency mismatch: {name} requires {requirement}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify-only", action="store_true")
    args = parser.parse_args()
    BUNDLE.mkdir(exist_ok=True)
    command = [
        sys.executable, "-m", "pip", "--isolated", "download",
        "--disable-pip-version-check", "--index-url", "https://pypi.org/simple",
        "--only-binary=:all:", "--no-deps", "--python-version", "3.12",
        "--implementation", "cp", "--abi", "cp312", "--abi", "abi3", "--abi", "none",
        "--platform", "manylinux2014_x86_64", "--platform", "manylinux_2_28_x86_64",
        "--platform", "manylinux_2_34_x86_64", "--dest", str(BUNDLE),
        "-r", str(API / "constraints-production.txt"),
    ]
    if not args.verify_only:
        subprocess.run(command, check=True)
    with ThreadPoolExecutor(max_workers=6) as pool:
        records = sorted(pool.map(verify, BUNDLE.glob("*.whl")))
    expected = {line.strip() for line in (API / "constraints-production.txt").read_text().splitlines()
                if line.strip() and not line.startswith("#")}
    actual = {f"{canonicalize_name(name)}=={version}" for name, version, _, _ in records}
    if expected != actual or len(records) != len(expected):
        raise ValueError("Bundle does not exactly match the approved version set")
    validate_dependencies(records)
    lock = "# Generated by tools/prepare_api_wheels.py; CPython 3.12 Linux x86_64.\n"
    lock += "\n".join(f"{name}=={version} --hash=sha256:{digest}" for name, version, digest, _ in records) + "\n"
    (BUNDLE / "requirements.lock").write_text(lock, encoding="utf-8")
    print(f"Verified {len(records)} official PyPI wheels; generated hash-locked offline artifact.")


if __name__ == "__main__":
    main()
